//! Synth patch schema. Consumed by `sonder-dsp`, referenced by name from scenes,
//! and definable inline in a scene's `[instruments.<name>]` table.
//!
//! Every field has a sensible default so presets can be terse:
//!
//! ```toml
//! [instruments."pluck.glass"]
//! osc = [{ wave = "triangle" }, { wave = "sine", octave = 1, level = 0.3 }]
//! filter = { kind = "lp", cutoff = 2400, resonance = 0.2, env_amount = 0.6 }
//! amp_env = { attack = 0.002, decay = 0.4, sustain = 0.0, release = 0.6 }
//! reverb_send = 0.4
//! ```

use serde::{Deserialize, Serialize};

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize, Default)]
#[serde(rename_all = "snake_case")]
pub enum Wave {
    #[default]
    Sine,
    Triangle,
    /// PolyBLEP anti-aliased sawtooth.
    Saw,
    /// PolyBLEP anti-aliased square.
    Square,
    /// Variable-width pulse (see [`Osc::pulse_width`]).
    Pulse,
    /// Seven detuned saws (see [`Osc::spread`]).
    Supersaw,
    /// Two-operator FM: carrier sine modulated by a sine at `fm_ratio` with `fm_index`.
    Fm,
    /// White noise.
    Noise,
    /// Pink (1/f) noise.
    Pink,
    /// Granular playback of the layer's live audio ring (see [`Grain`]); silent until
    /// audio arrives via `SynthCommand::AudioChunk`.
    Grain,
    /// Karplus–Strong plucked string (physical model).
    String,
    /// Modal resonator bank (struck bar / membrane / bell physical model).
    Modal,
    /// Band-limited single-cycle wavetable (see [`Osc::table`]).
    Wavetable,
}

/// Built-in single-cycle wavetables for [`Wave::Wavetable`]. Generated by
/// additive synthesis at startup in `sonder-dsp`, with mip levels per pitch range.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize, Default)]
#[serde(rename_all = "snake_case")]
pub enum Table {
    /// Drawbar organ: fundamental, octaves and a fifth.
    #[default]
    Organ,
    /// Vowel-like: two formant bumps over a 1/n spectrum.
    Vox,
    /// Sparse odd harmonics, bright and hollow.
    Glass,
    /// Prime-numbered harmonics with slow roll-off: clangy, bell-metal.
    Metal,
    /// 33% duty pulse (every third harmonic missing), nasal and reedy.
    Pulse3,
    /// First eight harmonics at 1/n: a soft, rounded saw.
    Sine8,
}

impl Table {
    pub const ALL: [Table; 6] = [Table::Organ, Table::Vox, Table::Glass, Table::Metal, Table::Pulse3, Table::Sine8];
}

/// One oscillator in a voice. Up to two per instrument.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[serde(default)]
pub struct Osc {
    pub wave: Wave,
    /// Linear level 0..1.
    pub level: f32,
    /// Octave offset (integer).
    pub octave: i8,
    /// Semitone offset.
    pub semitones: f32,
    /// Fine detune in cents.
    pub detune_cents: f32,
    /// Pulse width 0.05..0.95 for [`Wave::Pulse`].
    pub pulse_width: f32,
    /// Detune spread in cents for [`Wave::Supersaw`].
    pub spread: f32,
    /// Modulator/carrier ratio for [`Wave::Fm`].
    pub fm_ratio: f32,
    /// Modulation index for [`Wave::Fm`] (0 = pure sine).
    pub fm_index: f32,
    /// How much the amp envelope scales fm_index (bright attack → mellow tail).
    pub fm_index_env: f32,
    /// Which built-in table [`Wave::Wavetable`] reads.
    pub table: Table,
    /// Granular settings for [`Wave::Grain`].
    pub grain: Grain,
    /// Physical-model settings for [`Wave::String`] and [`Wave::Modal`].
    pub model: Model,
}

/// Settings for [`Wave::Grain`]: granular playback of the layer's live audio ring.
#[derive(Debug, Clone, Copy, PartialEq, Serialize, Deserialize)]
#[serde(default)]
pub struct Grain {
    /// How much recent audio the grains may reach back into, seconds (capped at 8).
    pub ring_seconds: f32,
    /// Grain length in milliseconds (Hann window).
    pub size_ms: f32,
    /// Grains started per second per voice.
    pub density: f32,
    /// Random start-position spread back into the ring, seconds.
    pub spray: f32,
    /// 0..1: how much the playback rate retunes the source's estimated pitch to the
    /// note (0 = play at the original speed, 1 = fully pitched to the note).
    pub pitch_follow: f32,
    /// Random per-grain pitch jitter in cents.
    pub jitter_cents: f32,
    /// 0..1 stereo spread of grain positions.
    pub width: f32,
}

impl Default for Grain {
    fn default() -> Self {
        Self { ring_seconds: 4.0, size_ms: 80.0, density: 20.0, spray: 0.5, pitch_follow: 1.0, jitter_cents: 0.0, width: 0.5 }
    }
}

/// Settings for the physical models [`Wave::String`] and [`Wave::Modal`].
#[derive(Debug, Clone, Copy, PartialEq, Serialize, Deserialize)]
#[serde(default)]
pub struct Model {
    /// 0..1 loss: 0 rings for seconds, 1 dies almost at once.
    pub damping: f32,
    /// 0..1 excitation brightness (noise-burst / strike colour).
    pub brightness: f32,
    /// 0..1 pick / strike position along the string or bar (0.5 = middle).
    pub position: f32,
    /// 0..1 partial series for [`Wave::Modal`]: 0 = harmonic, 1 = bell-like inharmonic.
    pub stiffness: f32,
    /// Number of resonators for [`Wave::Modal`], 1..32.
    pub modes: u8,
}

impl Default for Model {
    fn default() -> Self {
        Self { damping: 0.3, brightness: 0.7, position: 0.2, stiffness: 0.0, modes: 12 }
    }
}

impl Default for Osc {
    fn default() -> Self {
        Self {
            wave: Wave::Sine,
            level: 1.0,
            octave: 0,
            semitones: 0.0,
            detune_cents: 0.0,
            pulse_width: 0.5,
            spread: 12.0,
            fm_ratio: 2.0,
            fm_index: 1.0,
            fm_index_env: 0.0,
            table: Table::Organ,
            grain: Grain::default(),
            model: Model::default(),
        }
    }
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize, Default)]
#[serde(rename_all = "snake_case")]
pub enum FilterKind {
    Off,
    #[default]
    Lp,
    Hp,
    Bp,
}

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[serde(default)]
pub struct Filter {
    pub kind: FilterKind,
    /// Base cutoff in Hz.
    pub cutoff: f32,
    /// 0..1 resonance (mapped to Q by the synth).
    pub resonance: f32,
    /// Filter envelope depth in octaves (can be negative).
    pub env_amount: f32,
    /// 0..1: how much the cutoff follows note pitch.
    pub key_track: f32,
    /// LFO depth in octaves.
    pub lfo_amount: f32,
    /// Velocity → cutoff in octaves.
    pub velocity_amount: f32,
}

impl Default for Filter {
    fn default() -> Self {
        Self {
            kind: FilterKind::Lp,
            cutoff: 8000.0,
            resonance: 0.1,
            env_amount: 0.0,
            key_track: 0.0,
            lfo_amount: 0.0,
            velocity_amount: 0.0,
        }
    }
}

/// ADSR envelope, times in seconds, sustain 0..1.
#[derive(Debug, Clone, Copy, PartialEq, Serialize, Deserialize)]
#[serde(default)]
pub struct Adsr {
    pub attack: f32,
    pub decay: f32,
    pub sustain: f32,
    pub release: f32,
}

impl Default for Adsr {
    fn default() -> Self {
        Self { attack: 0.01, decay: 0.2, sustain: 0.8, release: 0.3 }
    }
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize, Default)]
#[serde(rename_all = "snake_case")]
pub enum LfoShape {
    #[default]
    Sine,
    Triangle,
    Saw,
    Square,
    /// Sample-and-hold random.
    Random,
}

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[serde(default)]
pub struct Lfo {
    pub shape: LfoShape,
    pub rate_hz: f32,
    /// Depth in cents.
    pub to_pitch: f32,
    /// Depth 0..1 (tremolo).
    pub to_amp: f32,
    /// Depth 0..1 (auto-pan).
    pub to_pan: f32,
    /// Depth 0..1 for pulse width.
    pub to_pulse_width: f32,
    /// Retrigger LFO phase on each note.
    pub retrigger: bool,
}

impl Default for Lfo {
    fn default() -> Self {
        Self {
            shape: LfoShape::Sine,
            rate_hz: 0.5,
            to_pitch: 0.0,
            to_amp: 0.0,
            to_pan: 0.0,
            to_pulse_width: 0.0,
            retrigger: false,
        }
    }
}

/// Per-layer chorus insert: 2–3 modulated delay taps on the layer bus, after the
/// voice mix and before the sends. `depth = 0` bypasses it entirely.
#[derive(Debug, Clone, Copy, PartialEq, Serialize, Deserialize)]
#[serde(default)]
pub struct Chorus {
    /// Modulation depth 0..1 (0 = bypass).
    pub depth: f32,
    /// LFO rate in Hz, 0.1..5.
    pub rate_hz: f32,
    /// Dry/wet 0..1.
    pub mix: f32,
    /// Number of delay taps, 2 or 3.
    pub voices: u8,
}

impl Default for Chorus {
    fn default() -> Self {
        Self { depth: 0.0, rate_hz: 0.6, mix: 0.5, voices: 2 }
    }
}

/// A complete synth patch.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[serde(default)]
pub struct Instrument {
    /// One or two oscillators. Empty = one default sine.
    pub osc: Vec<Osc>,
    pub filter: Filter,
    pub amp_env: Adsr,
    pub filter_env: Adsr,
    pub lfo: Lfo,
    /// Portamento time in seconds (0 = off). Only meaningful for mono-ish use.
    pub glide: f32,
    /// Output gain, linear.
    pub gain: f32,
    /// Default pan 0..1 (0.5 = center). Note-level pan is added as an offset.
    pub pan: f32,
    /// Stereo width 0..1 — spreads oscillators / unison across the field.
    pub width: f32,
    pub reverb_send: f32,
    pub delay_send: f32,
    /// Max simultaneous voices for this instrument.
    pub polyphony: u8,
    /// 0..1 how much velocity scales amplitude (0 = fixed level).
    pub velocity_to_amp: f32,
    /// Soft saturation drive 0..1 applied post-filter.
    pub drive: f32,
    /// Layer-bus chorus (bypassed by default).
    pub chorus: Chorus,
    /// Optional hint for the UI.
    pub description: String,
}

impl Default for Instrument {
    fn default() -> Self {
        Self {
            osc: vec![Osc::default()],
            filter: Filter::default(),
            amp_env: Adsr::default(),
            filter_env: Adsr { attack: 0.01, decay: 0.3, sustain: 0.0, release: 0.3 },
            lfo: Lfo::default(),
            glide: 0.0,
            gain: 0.8,
            pan: 0.5,
            width: 0.0,
            reverb_send: 0.2,
            delay_send: 0.0,
            polyphony: 8,
            velocity_to_amp: 0.7,
            drive: 0.0,
            chorus: Chorus::default(),
            description: String::new(),
        }
    }
}

/// Percussion sounds are synthesized, not sampled. The composer picks one of
/// these per hit; `sonder-dsp` owns the recipes.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum Drum {
    Kick,
    Snare,
    Hat,
    /// Short filtered click / tick.
    Click,
    /// Noise burst, length from velocity.
    Noise,
    /// Pitched tom-like body.
    Tom,
    /// Metallic rimshot-ish.
    Rim,
}

impl Drum {
    pub fn parse(s: &str) -> Option<Drum> {
        Some(match s.trim().to_ascii_lowercase().as_str() {
            "kick" => Drum::Kick,
            "snare" => Drum::Snare,
            "hat" | "hihat" => Drum::Hat,
            "click" | "tick" => Drum::Click,
            "noise" => Drum::Noise,
            "tom" => Drum::Tom,
            "rim" => Drum::Rim,
            _ => return None,
        })
    }
}

/// Settings for the shared effect buses and master chain.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize, Default)]
#[serde(default)]
pub struct Effects {
    pub reverb: ReverbSettings,
    pub delay: DelaySettings,
    pub master: MasterSettings,
}

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[serde(default)]
pub struct ReverbSettings {
    /// 0..1 room size / decay.
    pub size: f32,
    /// 0..1 high-frequency damping.
    pub damping: f32,
    /// Pre-delay in ms.
    pub predelay_ms: f32,
    /// Return level 0..1.
    pub level: f32,
    /// Low-cut on the wet signal, Hz.
    pub lowcut_hz: f32,
}

impl Default for ReverbSettings {
    fn default() -> Self {
        Self { size: 0.8, damping: 0.4, predelay_ms: 20.0, level: 0.8, lowcut_hz: 150.0 }
    }
}

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[serde(default)]
pub struct DelaySettings {
    /// Delay time in beats (tempo-synced). E.g. 0.75 = dotted eighth.
    pub beats: f32,
    pub feedback: f32,
    /// Ping-pong between channels.
    pub ping_pong: bool,
    /// Low-pass on the feedback path, Hz.
    pub damp_hz: f32,
    pub level: f32,
}

impl Default for DelaySettings {
    fn default() -> Self {
        Self { beats: 0.75, feedback: 0.35, ping_pong: true, damp_hz: 4000.0, level: 0.7 }
    }
}

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[serde(default)]
pub struct MasterSettings {
    pub gain: f32,
    /// Soft saturation 0..1.
    pub saturation: f32,
    /// Limiter ceiling in dBFS (negative).
    pub ceiling_db: f32,
    /// Loudness target in LUFS (e.g. -16 for streaming); the master rides gain slowly
    /// toward it. None = off.
    pub target_lufs: Option<f32>,
    /// Bus compressor amount 0..1 (0 = off): gentle glue, slow release.
    pub glue: f32,
}

impl Default for MasterSettings {
    fn default() -> Self {
        Self { gain: 0.9, saturation: 0.1, ceiling_db: -1.0, target_lufs: Some(-16.0), glue: 0.25 }
    }
}
